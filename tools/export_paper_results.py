"""Rebuild paper tables/macros and end-to-end summaries from released CSVs.

Run at the repository root with the scientific Python environment.
Paired tests use per-instance means, rounded to 10 decimal places to avoid
floating-point zero/rank artefacts. Speed tests select instances with >0 rejects.
"""
from pathlib import Path
import hashlib
import json
import re
import numpy as np
import pandas as pd
from scipy.stats import wilcoxon, spearmanr

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT/'analysis_la_cetsp/results'
TEST = ROOT/'analysis_test'
OUT = ROOT/'paper/generated'
OUT.mkdir(exist_ok=True)
NAMES = {'BASELINE':'Baseline (no ML)', 'COX':'Cox PH', 'RSF':'RSF',
         'KNN':'KNN', 'ELASTICNET':'ElasticNet', 'WEIBULLAFT':'WeibullAFT',
         'GBSA':'GBSA', 'DEEPSURV':'DeepSurv', 'MTLR':'MTLR', 'SSVM':'SSVM'}

def rows(name, lines):
    if name.endswith('_rows.tex'):
        lines = lines + [r'\bottomrule']
    (OUT/name).write_text('% Generated by tools/export_paper_results.py\n'+
                         '\n'.join(lines)+'\n', encoding='utf-8')

def test(diff):
    diff = np.round(np.asarray(diff, float), 10)
    n = int(np.count_nonzero(diff))
    return n, float(wilcoxon(diff, zero_method='wilcox', method='approx').pvalue) if n else 1.

d = pd.read_csv(TEST/'parsed/island_summaries.csv')
assert not d.duplicated(['instance','run','model']).any()
assert len(d) == 2650 and d.instance.nunique() == 53
assert (d.groupby(['instance','model']).size() == 5).all()
base = d[d.model == 'BASELINE'][['instance','run','best','total_t']]
p = d.merge(base, on=['instance','run'], suffixes=('','_base'), validate='many_to_one')
p['degradation%'] = 100*(p.best/p.best_base - 1)
p['speedup'] = p.total_t_base/p.total_t
p['reject_rate%'] = 100*p.ml_rejects/p.effective_iter
active = set(d.groupby('instance').ml_rejects.sum().loc[lambda x:x > 0].index)
assert len(active) == 47
summaries = {}
for name, frame in [('full', p), ('active', p[p.instance.isin(active)])]:
    table = frame.groupby('model').agg(mean_best=('best','mean'),
        **{c:(c,'mean') for c in ['degradation%','speedup','reject_rate%']},
        n_instances=('instance','nunique')).reset_index()
    table.to_csv(TEST/f'results/model_comparison_{name}.csv',index=False)
    summaries[name] = table
table = summaries['full'].set_index('model')
order = ['BASELINE']+table.drop('BASELINE').sort_values('degradation%').index.tolist()
rows('model_rows.tex', [f"{NAMES[m]} & {table.loc[m,'mean_best']:.3f} & "
    f"${table.loc[m,'degradation%']:+.3f}$ & {table.loc[m,'speedup']:.3f} & "
    f"{table.loc[m,'reject_rate%']:.2f} \\\\" for m in order])
means = d.groupby(['instance','model'])[['best','total_t']].mean()
stats = []
for m in order[1:]:
    diff = means.xs(m,level='model') - means.xs('BASELINE',level='model')
    nq,pq = test(diff.best)
    nt,pt = test(diff.loc[sorted(active),'total_t'])
    stats.append(dict(model=m,quality_n_eff=nq,quality_p=pq,quality_sig=pq<.05,
                      speed_n_eff=nt,speed_p=pt,speed_sig=pt<.05))
stats = pd.DataFrame(stats).sort_values('quality_p')
stats.to_csv(TEST/'results/wilcoxon_test.csv',index=False)
rows('wilcoxon_rows.tex', [f"{NAMES[r.model]} & {r.quality_n_eff} & {r.quality_p:.3f} & "
    f"{r.speed_n_eff} & {r.speed_p:.3f} \\\\" for r in stats.itertuples()])
ml = d[d.model != 'BASELINE'].copy()
ml['window'] = np.maximum(ml.effective_iter-1000,0)
trigger = ml[ml.effective_iter >= 1000]
trigger.groupby('model').agg(n_runs=('run','size'),mean_rejects=('ml_rejects','mean'),
    median_rejects=('ml_rejects','median'),total_rejects=('ml_rejects','sum')).to_csv(
        TEST/'results/filter_activity.csv')
activity = dict(ml_runs=len(ml),before_trigger=int((ml.effective_iter<1000).sum()),
    at_trigger=int((ml.effective_iter==1000).sum()),trigger_reaching=len(trigger),
    median_window=float(trigger.window.median()),
    median_window_fraction=float((trigger.window/trigger.effective_iter).median()),
    instances_with_rejection=len(active))
(TEST/'results/filter_activity.json').write_text(json.dumps(activity,indent=2)+'\n')

stages = pd.read_csv(RES/'rank_transmission.csv')
def texname(value):
    return value.replace('_',r'\_')
rows('stage_rows.tex', [f"{texname(r.instance)} & ${r.global_rho:+.2f}$ & "
     f"${r.cohort_rho:+.2f}$ \\\\" for r in stages.itertuples()])
k = pd.read_csv(RES/'kappa_calibration.csv')
obs = pd.read_csv(RES/'kappa_observed.csv')
rows('kappa_rows.tex', [f"{r.kappa:.2f} & {r.kappa_mean:.3f} & {r.C_mean:.3f} & "
    f"{r.C_std:.3f} \\\\" for r in k.itertuples()])
macros = {'KappaVNDMean':obs.kappa_observed.mean(),'KappaVNDMin':obs.kappa_observed.min(),
    'KappaVNDMax':obs.kappa_observed.max(),'ObservedRankC':obs.C_observed.mean(),
    'CalibrationStartC':k.C_mean.iloc[0],'CalibrationEndC':k.C_mean.iloc[-1]}
for prefix,col in [('Greedy','greedy_rho'),('LkhRank','lkh_rho'),('Refine','refine_rho'),
                   ('GlobalRank','global_rho'),('CohortRank','cohort_rho')]:
    macros[prefix+'Min']=stages[col].min(); macros[prefix+'Max']=stages[col].max()
lkh = pd.read_csv(RES/'contraction_kappa.csv').set_index('instance')
for name,inst in [('LkhCircle','concentricCircles4'),('LkhKro','kroD100_or2'),('LkhRat','rat195_or30')]:
    macros[name]=lkh.loc[inst,'kappa']
rho,pval = spearmanr(table.drop('BASELINE')['reject_rate%'],table.drop('BASELINE').speedup)
macros['RejectionSpeedRho']=rho; macros['RejectionSpeedP']=pval
rows('results.tex',[rf'\newcommand{{\{key}}}{{{value:.3f}}}' for key,value in macros.items()])

defs = (ROOT/'include/Defs.hpp').read_text()
universe = re.findall(r'"([^"]+)"',defs.split('FILENAMES = {')[1].split('};')[0])
assert len(universe) == 68
manifest = pd.DataFrame({'instance':universe})
manifest['split'] = np.where(manifest.instance.isin(d.instance), 'test','development')
for label,source in [('model','model_ceiling.csv'),('oracle','oracle_ceiling_per_instance.csv'),
                     ('lineage','lineage_signal_per_instance.csv'),('stage','rank_transmission.csv'),
                     ('kappa_vnd','kappa_observed.csv')]:
    manifest[label] = manifest.instance.isin(pd.read_csv(RES/source).instance)
assert ((manifest.split == 'development') & manifest.kappa_vnd).sum() == 8
manifest.to_csv(RES/'instance_manifest.csv',index=False)
files = [TEST/'parsed/island_summaries.csv', TEST/'parsed/thresholds.csv',
         TEST/'parsed/training_events.csv',TEST/'parsed/convergence.csv']
files += sorted(RES.glob('*.csv'))
pd.DataFrame([dict(path=str(f.relative_to(ROOT)).replace('\\','/'),
    sha256=hashlib.sha256(f.read_bytes()).hexdigest()) for f in files]).to_csv(
        OUT/'input_hashes.csv',index=False)
print(stats.to_string(index=False))
print(activity)
print('Updated generated paper inputs, summaries and instance manifest.')
